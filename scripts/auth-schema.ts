/**
 * Writes the D1 migration for better-auth's tables (users, sessions,
 * accounts, verification tokens, rate limits) from the options in
 * worker/auth-options.ts, by diffing them against an empty in-memory SQLite.
 *
 *   node scripts/auth-schema.ts > migrations/0001_auth.sql
 *
 * Run it again after a better-auth upgrade or an options change, and save
 * only the difference as a new numbered migration.
 */
import { DatabaseSync } from "node:sqlite";
import { getMigrations } from "better-auth/db/migration";
import { magicLink } from "better-auth/plugins";
import { authOptions } from "../worker/auth-options.ts";

const { compileMigrations } = await getMigrations({
  ...authOptions,
  database: new DatabaseSync(":memory:"),
  plugins: [magicLink({ sendMagicLink: () => {} })],
});
process.stdout.write(`-- Generated by scripts/auth-schema.ts (better-auth). Do not edit.\n${await compileMigrations()}\n`);
